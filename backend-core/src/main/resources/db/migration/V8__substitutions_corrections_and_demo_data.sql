ALTER TABLE users ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;

-- Czasowe zastępstwo oceniającego (BPMN: zastępstwa; eskalacja ZASTEPCA). Daty włącznie.
CREATE TABLE evaluator_substitutions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id    BIGINT       NOT NULL REFERENCES offices (id),
    evaluator_id BIGINT       NOT NULL REFERENCES users (id),
    deputy_id    BIGINT       NOT NULL REFERENCES users (id),
    start_date   DATE         NOT NULL,
    end_date     DATE         NOT NULL,
    reason       VARCHAR(500) NOT NULL,
    created_by   BIGINT       NOT NULL REFERENCES users (id),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date),
    CHECK (evaluator_id <> deputy_id)
);
CREATE INDEX idx_substitutions_deputy ON evaluator_substitutions (deputy_id, start_date, end_date);
CREATE INDEX idx_substitutions_evaluator ON evaluator_substitutions (evaluator_id, start_date, end_date);

-- Dane poprzedniej oceny wpisane ręcznie w arkuszu, gdy brak jej w historii (schemat pól A/B/C, cz. II).
ALTER TABLE evaluation_cycles
    ADD COLUMN prev_evaluation_outcome VARCHAR(16) CHECK (prev_evaluation_outcome IN ('POSITIVE', 'NEGATIVE')),
    ADD COLUMN prev_evaluation_level   VARCHAR(32) CHECK (prev_evaluation_level IN ('SIGNIFICANTLY_BELOW', 'BELOW', 'MEETS', 'ABOVE', 'SIGNIFICANTLY_ABOVE')),
    ADD COLUMN prev_evaluation_date    DATE;

