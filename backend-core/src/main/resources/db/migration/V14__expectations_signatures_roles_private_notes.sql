-- Oczekiwania dla kryteriów (§ 5 ust. 1 pkt 3: opis zachowań na poziomie „5 pkt — na poziomie oczekiwań”),
-- trzy tryby podpisu, łączenie ról w małym urzędzie i prywatny dziennik pracownika.

ALTER TABLE evaluation_cycles
    ADD COLUMN criteria_expectations_json   JSONB,
    ADD COLUMN signature_hash               VARCHAR(64),
    ADD COLUMN signature_verification_code  VARCHAR(20),
    ADD COLUMN signed_at                    TIMESTAMPTZ,
    ADD COLUMN paper_signed_on              DATE,
    ADD COLUMN scan_reference               VARCHAR(255);

-- Nowe tryby obok dotychczasowych wartości (zachowanych dla istniejących arkuszy i klientów API).
ALTER TABLE evaluation_cycles DROP CONSTRAINT evaluation_cycles_signature_method_check;
ALTER TABLE evaluation_cycles ADD CONSTRAINT evaluation_cycles_signature_method_check CHECK (signature_method IN
    ('QUALIFIED_OR_TRUSTED', 'INTERNAL_AUDIT_STAMP', 'HYBRID_PAPER_SCAN', 'MOBYWATEL_QES', 'PAPER_HYBRID', 'SYSTEM_DEMO'));

-- Role dodatkowe (np. kierownik małego urzędu: DG + EVALUATOR + HR), lista rozdzielona przecinkami; bez KPRM_ADMIN.
ALTER TABLE users ADD COLUMN secondary_roles VARCHAR(128) NOT NULL DEFAULT ''
    CHECK (secondary_roles !~ 'KPRM_ADMIN');

-- Prywatny dziennik pracownika — dostęp wyłącznie właściciela; nie jest częścią akt ani paczki EZD.
CREATE TABLE employee_private_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    cycle_id   BIGINT REFERENCES evaluation_cycles (id) ON DELETE SET NULL,
    content    TEXT        NOT NULL CHECK (char_length(content) BETWEEN 1 AND 10000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ
);
CREATE INDEX idx_private_notes_owner ON employee_private_notes (owner_id, created_at);
