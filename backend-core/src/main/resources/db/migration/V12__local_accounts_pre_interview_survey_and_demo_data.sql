-- Etap 2: konta lokalne (login + hasło BCrypt) dla małych urzędów bez Węzła Krajowego / AD, ankieta przygotowawcza
-- przed rozmową (niezależna od anonimowej ankiety dobrostanu), schemat v2 z kryteriami własnymi.

ALTER TABLE users
    ADD COLUMN password_hash       VARCHAR(100),
    ADD COLUMN password_changed_at TIMESTAMPTZ;

-- Tryb Mały Urząd: logowanie loginem i hasłem dostępne dla kont urzędu (obok symulacji WK/PZ i AD).
ALTER TABLE offices ADD COLUMN local_auth_enabled BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE offices SET local_auth_enabled = TRUE WHERE id = 2;

-- Ankieta przygotowawcza: pytania domyślne ze schematu + własne pytania kadr / przełożonego; odpowiedzi ocenianego
-- trafiają do przełożonego dopiero po „Wyślij przełożonemu”. Dane pomocnicze — nie wchodzą do akt osobowych.
CREATE TABLE pre_interview_surveys (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id       BIGINT      NOT NULL UNIQUE REFERENCES evaluation_cycles (id) ON DELETE CASCADE,
    questions_json JSONB       NOT NULL,
    status         VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SENT')),
    sent_at        TIMESTAMPTZ,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Schemat v2 (od 2027-01-01): katalog i progi jak v1, kryteria własne dopuszczone; ankieta z pytaniami własnymi.
-- v1 (urzędowy arkusz) pozostaje bez zmian: criteriaRules.allowCustom = false.
INSERT INTO schema_versions (version_code, effective_from, period_months, config_json, created_by)
SELECT 'v2', DATE '2027-01-01', period_months,
       jsonb_set(jsonb_set(config_json, '{criteriaRules,allowCustom}', 'true'::jsonb, true),
                 '{preInterviewSurvey}', '{"allowCustom": true}'::jsonb, true),
       created_by
FROM schema_versions WHERE version_code = 'v1';
