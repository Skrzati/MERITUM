CREATE TABLE offices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    has_dg_role BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id        BIGINT       NOT NULL REFERENCES offices (id),
    full_name        VARCHAR(255) NOT NULL,
    email            VARCHAR(255) NOT NULL UNIQUE,
    role             VARCHAR(32)  NOT NULL CHECK (role IN ('EVALUATOR', 'EVALUATED', 'HR', 'DG', 'KPRM_ADMIN')),
    is_civil_servant BOOLEAN      NOT NULL DEFAULT FALSE,
    supervisor_id    BIGINT REFERENCES users (id)
);
CREATE INDEX idx_users_office ON users (office_id);
CREATE INDEX idx_users_supervisor ON users (supervisor_id);

CREATE TABLE schema_versions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_code   VARCHAR(64) NOT NULL UNIQUE,
    effective_from DATE        NOT NULL,
    period_months  INT         NOT NULL CHECK (period_months > 0),
    config_json    JSONB       NOT NULL,
    created_by     BIGINT REFERENCES users (id)
);

CREATE TABLE evaluation_cycles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id          BIGINT      NOT NULL REFERENCES offices (id),
    employee_id        BIGINT      NOT NULL REFERENCES users (id),
    evaluator_id       BIGINT      NOT NULL REFERENCES users (id),
    schema_version_id  BIGINT      NOT NULL REFERENCES schema_versions (id),
    sheet_type         VARCHAR(1)  NOT NULL CHECK (sheet_type IN ('A', 'B', 'C')),
    status             VARCHAR(32) NOT NULL CHECK (status IN ('DRAFT_CRITERIA', 'CRITERIA_CONFIRMED', 'OBSERVATION',
                                                              'EVALUATION_DRAFT', 'AWAITING_ACK', 'COMPLETED', 'APPEALED')),
    start_date         DATE        NOT NULL,
    due_date           DATE        NOT NULL,
    criteria_json      JSONB,
    scores_json        JSONB,
    average_score      NUMERIC(4, 2),
    final_result       VARCHAR(64),
    justification      TEXT,
    iprz_notes         TEXT,
    grade_request_json JSONB
);
CREATE INDEX idx_cycles_office ON evaluation_cycles (office_id);
CREATE INDEX idx_cycles_employee ON evaluation_cycles (employee_id);
CREATE INDEX idx_cycles_evaluator ON evaluation_cycles (evaluator_id);

CREATE TABLE employee_notes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id             BIGINT      NOT NULL REFERENCES evaluation_cycles (id) ON DELETE CASCADE,
    author_id            BIGINT      NOT NULL REFERENCES users (id),
    content              TEXT        NOT NULL,
    is_shared_after_eval BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notes_cycle ON employee_notes (cycle_id);

CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id    BIGINT REFERENCES offices (id),
    actor_id     BIGINT REFERENCES users (id),
    action       VARCHAR(64) NOT NULL,
    entity_type  VARCHAR(64) NOT NULL,
    entity_id    BIGINT,
    payload_json JSONB,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_office_created ON audit_logs (office_id, created_at);
