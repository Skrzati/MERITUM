-- Etap 8A: bieżąca informacja zwrotna (Standardy ZZL), strukturalny IPRZ i jego zatwierdzanie (art. 108 ustawy o SC).

CREATE TABLE feedback_checkins (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id             BIGINT       NOT NULL REFERENCES evaluation_cycles (id) ON DELETE CASCADE,
    author_id            BIGINT       NOT NULL REFERENCES users (id),
    conducted_on         DATE         NOT NULL,
    topic                VARCHAR(255) NOT NULL,
    summary              TEXT         NOT NULL,
    next_steps           TEXT,
    shared_with_employee BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_checkins_cycle ON feedback_checkins (cycle_id, conducted_on);

CREATE TABLE iprz_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id       BIGINT       NOT NULL REFERENCES evaluation_cycles (id) ON DELETE CASCADE,
    criterion_code VARCHAR(16),
    action_title   VARCHAR(500) NOT NULL,
    form_type      VARCHAR(16)  NOT NULL CHECK (form_type IN ('SZKOLENIE', 'MENTORING', 'SAMOKSZTALCENIE', 'PROJEKT', 'INNE')),
    target_date    DATE,
    status         VARCHAR(16)  NOT NULL DEFAULT 'PLANNED' CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'DONE')),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_iprz_cycle ON iprz_items (cycle_id);

ALTER TABLE evaluation_cycles
    ADD COLUMN iprz_status          VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK (iprz_status IN ('DRAFT', 'PROPOSED', 'APPROVED')),
    ADD COLUMN iprz_approved_by     BIGINT REFERENCES users (id),
    ADD COLUMN iprz_approved_at     TIMESTAMPTZ,
    ADD COLUMN iprz_employee_ack_at TIMESTAMPTZ;

